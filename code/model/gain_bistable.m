function [dG, phi] = gain_bistable(G, h, p)
% GAIN_BISTABLE  三个突触增益共用的双稳（三次型）增益方程
%
%   [dG, phi] = gain_bistable(G, h, p)
%
% 输入
%   G    3×1 当前增益 (mV)，顺序 [G_e; G_s; G_f]
%   h    标量，归一化活动驱动 ∈ (0,1)，见 wendling.derivatives：
%        h = S(y_out) / (2·e0)，即锥体细胞群体的瞬时发放率（未整流、未减阈值）
%   p    参数结构体，每个字段都是 3×1（一行一个增益）：
%          Glo       φ=0 时的增益值 (mV)
%          span      φ=1 相对 φ=0 的变化量 (mV)；取负表示"病理方向是增益下降"
%          phi0      静息态对应的 φ
%          phi_thr   双稳阈值对应的 φ（φ 必须越过它才会跳向上支）
%          A         三次项速率 (1/s)
%          B         活动驱动增益 (1/s)
%          hc        活动阈值（h 超过它才开始推动 φ 上移）
%          C0        基础恢复速率 (1/s)
%          C1        活动相关恢复速率 (1/s)
%
% 输出
%   dG   3×1 增益的导数 (mV/s)，可直接作为 dy_ESF 返回
%   phi  3×1 归一化增益
%
% 方程（三个增益完全同一个式子，只有参数不同）
%
%   dφ/dt = (1−φ)·A·(φ−φ0)·(φ−φthr) + B·(h − hc) − (C0 + C1·h)·(φ − φ0)
%
% 三项的含义
%   1. (1−φ)·A·(φ−φ0)·(φ−φthr)：双稳核心，形式取自 Yang et al. (2021,
%      Cogn. Neurodyn. 15:43) 的短时程可塑性方程 Ẇ=(1−W)[a(W−W0)(W−Wth)]+b·S·S。
%      它给出两个稳定点（φ0 与 φ≈1）与一个不稳定点 φthr：
%        φ<φ0        dφ/dt>0（下支有下界，不会掉出物理范围）
%        φ0<φ<φthr  dφ/dt<0（回到 φ0）
%        φ>φthr     dφ/dt>0（跑到 φ≈1，即"闩锁"）
%      注意 φ=1 处 (1−φ)=0，因此上支不需要任何钳位就自带饱和。
%   2. B·(h−hc)：活动驱动。h 低于 hc 时把 φ 压回 φ0，高于 hc 时把 φ 往上推；
%      当 B(h−hc)/C0 超过 φthr−φ0 时 φ 越过 φthr，双稳项接管 → 闩锁。
%      这里不出现 max(0,·)、不出现 if，也没有"不可逆标志"。
%   3. −(C0 + C1·h)·(φ−φ0)：慢恢复。C0 决定一次发作的持续时间，
%      C1 让"活动越强恢复越快"（活动依赖性耗竭），两项目前都按常数处理。
%
% 与旧实现（wendling.derivatives 的 legacy 分支）的关系
%   旧实现是"分段线性 + 三个独立状态机 + 阈值翻转 + 边界钳位"：
%       未翻转：dG = k1·x − k3·(G−G_rest)
%       已翻转：dG = −k2·x + k3·(G_rest−G)，x = max(0, y_out−y_thr)
%   本函数把它的三个要点保留下来，但换成连续形式：
%     · 正向驱动      → B·(h−hc)         （h 不整流，负向 PSP 也参与，见 E1）
%     · 阈值翻转      → 三次项的不稳定点 φthr（连续，无 if、无 inv 标志）
%     · 边界钳位      → (1−φ) 因子自带饱和，φ<φ0 一侧由三次项自动反弹
%   换来的是：derivatives 变成纯函数（不再修改对象状态），RK4 四个斜率属于
%   同一个方程（修掉 E2），也不再依赖 S==S_min 这类浮点精确相等（修掉 E3）。
%
% 调用关系
%   上游：wendling.derivatives（gain_law = 'bistable' 时）
%   下游：无
%
% 备注
%   span 取负时 φ 增大对应增益减小，dG = span·dφ 会自动带正确的符号，
%   所以"兴奋性增益往上跑、抑制性增益往下跑"可以用同一个式子表达。

phi  = (G(:) - p.Glo) ./ p.span;
dphi = (1 - phi) .* p.A .* (phi - p.phi0) .* (phi - p.phi_thr) ...
     + p.B .* (h - p.hc) ...
     - (p.C0 + p.C1 .* h) .* (phi - p.phi0);
dG   = p.span .* dphi;
end
